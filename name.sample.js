// ================================================================
//  name.sample.js ― 名前の一覧（pc-images/name.js）の見本
// ----------------------------------------------------------------
//  1-1 で入れた名前を、この一覧と照らします（PCで index.html を直接開いたときだけ）。
//  一覧にない名前なら、イーブイが聞き直します（設計書 1-1）。
//
//  【使い方】
//    1. このファイルをコピーして、pc-images フォルダ（index.html と同じ場所）に入れる
//    2. コピーしたファイルの名前を name.js に変える（pc-images/name.js）
//    3. 下の names・family・guess を、本当の名前に書きかえる（いまは架空の名前です）
//    4. 文字コードを「UTF-8」にして保存する
//    5. ?debug を付けて開き、🛠 の「PCだけのフォルダ」で「読みこめた」と出るか確かめる
//
//  ※ 本当の名前を書いた name.js は、GitHub に入れないでください。
//     pc-images フォルダは .gitignore で外していますが、GitHub のサイトから手でアップロードすると公開されます。
//  ※ この見本（name.sample.js）は、ゲームからは読みこみません。
//  ※ name.js がないときは、名前を確認せずに進みます（今までどおり）。
//  ※ iPhone（2-4 でブラッキーが聞く名前）は、確認しません。
//
//  【比べ方】
//    ・空白（全角・半角）を除いて比べます。「山田 太郎」と「山田太郎」は同じです。
//    ・カタカナはひらがなにそろえて比べます。「タロウ」と「たろう」は同じです。
//    ・全角と半角、ローマ字の大文字と小文字のちがいも、同じとみなします。
//    ・「名字＋名前」で入れても通します（family の名字と、names の名前の組み合わせ）。
//    ・通ったときは、入れたとおりの表記が、ゲームの中の名前（{name}）になります。
//
//  【よくある書きまちがい】
//    ・名前を囲む「"」の閉じ忘れ、名前と名前のあいだの「,」の付け忘れ
//    まちがえると、名前を確認せずに進みます（🛠 で「読めない」と出ます）。
// ================================================================
const NAME_LIST = {
  // 通す名前（下の名前）。ひらがな・漢字・ローマ字など、いくつでも書けます
  //   カタカナはひらがなと同じに比べるので、ひらがなで書けばカタカナでも通ります
  names: ["たろう", "太郎", "taro"],

  // 名字。「名字＋名前」で入れても通します（例：やまだたろう・山田太郎・山田 太郎・山田たろう）
  //   使わないときは []
  family: ["やまだ", "山田", "yamada"],

  // 3回続けて一覧にない名前だったときに、イーブイが「もしかして、○○？」と聞く呼び名
  //   「うん」を選ぶと、この呼び名がゲームの中の名前になります
  guess: "たろう",
};
