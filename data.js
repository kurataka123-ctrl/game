// ================================================================
//  data.js ― ゲームの文章とデータ
//             （セリフ・選択肢・合言葉・カード・画面の文字）
// ----------------------------------------------------------------
//  文章を変えたいときは、このファイルだけを編集します。
//  ゲームを動かす仕組み（engine.js）には、文章を書きません。
//  保存するときの文字コードは「UTF-8」にしてください。
//
//  【会話の書き方】
//    "イーブイ：こんにちは！"  → イーブイのセリフ（名前と「：」で始める）
//    "森の中は静かだった。"     → 名前がない行は地の文（ナレーション）
//    "\n" と書くと、その位置で改行します。
//    { } で囲んだ言葉は、ゲームが置きかえます。
//      {name}    → 主人公の名前（1-1 のPC、2-4 のiPhoneで入力したもの）
//      {friend1} → 友達の呼び名（遊ぶ前にPCで入れておく。SETTINGS の local）
//      {station} → 鏡に書く駅名（SETTINGS の hidden から）
//      {park}    → リーフィアのいる公園の名前（同上）
//
//  【条件つきの行】 設定や選んだ道によって、出す行を変えます
//    { if: "indoor", text: "サンダース：……" }      → indoor のときだけ出す
//    { unless: "indoor", text: "サンダース：……" }  → indoor ではないときだけ出す
//    条件の名前は、選択肢や場面の set で記録したもの（例：indoor）か、
//    SETTINGS の true / false の設定（例：useMirror）です。
//    選択肢（choices）にも、同じように if / unless を書けます。
//
//  【場面（シーン）の書き方】 くわしくは README.md を参照
//    lines   : 会話の行（上から順に表示）
//    next    : 会話が終わったら進む場面の名前
//    choices : 選択肢（next がない選択肢は、reply を表示してから選び直し）
//    input   : 文字を入力させる（なぞなぞ・カードの言葉・名前など）
//    end     : 章の終わりの画面を出す
//    mode    : "chat" にするとメッセージアプリ風（iPhone向け）の表示
//    bg      : 背景（forest / ice / memory / night / dream / home /
//              station / park / christmas）
//    meet    : この場面で、なかまノートに記録するポケモン
//    give    : 会話のあとに、そのポケモンの「言葉」を手に入れる
//    show    : 画面に出すキャラクター（4匹以上なら小さく並べる）
//    room    : true で room.js の地図を調べる、"dark" で暗い部屋、
//              "look" で地図を見せるだけ
//    ice     : 氷の床のパズル（書き方は glaceon の場面を参照）
//    walk    : 歩けるマップ（house.js の地図の名前）。人物と出来事は events に書く
//              （書き方は sylveon の場面と README の「歩けるマップ」を参照）
//    events  : 歩けるマップの人物・出入口と、そこで起きること（say・set・next）
//    start / goal / team : 歩き始める場所・画面に出す目的・集まった仲間の表示
//    battle  : 戦い（下の BATTLES の名前）。会話のあとに戦いが始まり、勝つと next へ進む
//    puzzle  : true で最後の謎の枠（下の PUZZLE）を表示する
//    set     : 条件の名前を記録する（unset で消す）。選択肢にも書ける
//    draft   : true にすると画面に「仮の内容」と表示（作りかけの目印）
//
//  【よくある書きまちがい】
//    ・行の終わりのカンマ「,」を忘れる
//    ・文章を囲む「"」を閉じ忘れる
//    画面に「シナリオを読み込めませんでした」と出たら、直前の編集箇所を確認。
//
//  ※ draft: true の場面は、仮の内容です（あとで変えてよい）。
//  ※ 公開したページは、URLを知っている人なら誰でも読めます。
//     名前・住所・駅名など、書きたくない情報は書かないでください。
//     答えは「暗号」に、画面に出したい地名は「表示用に隠す」形にします
//     （README の「答えを暗号にする」）。
// ================================================================


