//    ・相手のハート（enemy の hearts）を 0 にしたら勝ち。
//    ・数値は固定で、乱数は使わない（同じ選び方をすれば、いつも同じ結果になる）。
//
//  ※【仮】の数値・技・セリフは、あとで差し替えてかまいません。
//    変えたら ?debug の 🛠 で「戦いの点検」を見てください。戦いごとに、何ターンで勝てるか・
//    攻撃だけだとどうなるか・大技の予告のときだけ防ぐとどうなるか・でたらめに選ぶと何%勝てるかを、
