//
//  【決まり】
//    ・毎ターン、戦う仲間それぞれのコマンド（commands）を選ぶ。選び終わると、party の上から順に動く。
//      commands のかわりに tactics（さくせん）を書いた仲間は、自動で動く（合体戦のイーブイとニンフィア）。
//    ・相手は、actions を上から順にくり返す（ターンの終わりに動く）。
//    ・ハートは、みんなで共通（hearts）。0 になったら負け。
